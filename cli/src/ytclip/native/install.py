"""Register the native messaging host with Chrome/Chromium/Brave for the current user."""

from __future__ import annotations

import json
import os
import shlex
import sys
from dataclasses import dataclass
from pathlib import Path

from ytclip.native import DEFAULT_EXTENSION_ID, HOST_NAME

_BROWSER_DIRS = {
    "Google Chrome": ".config/google-chrome",
    "Chromium": ".config/chromium",
    "Brave": ".config/BraveSoftware/Brave-Browser",
}
_EXTENSION_ID_CHARS = set("abcdefghijklmnop")


@dataclass
class ManifestLocation:
    browser: str
    path: Path


def manifest_locations(home: Path | None = None, include_missing: bool = False) -> list[ManifestLocation]:
    """Chrome is always included; other browsers only when their profile exists."""
    home = home or Path.home()
    out = []
    for browser, rel in _BROWSER_DIRS.items():
        base = home / rel
        if browser == "Google Chrome" or base.exists() or include_missing:
            out.append(ManifestLocation(browser, base / "NativeMessagingHosts" / f"{HOST_NAME}.json"))
    return out


def validate_extension_id(extension_id: str) -> str:
    if len(extension_id) != 32 or not set(extension_id) <= _EXTENSION_ID_CHARS:
        raise ValueError(f"'{extension_id}' is not a Chrome extension ID (32 letters a-p)")
    return extension_id


def write_launcher(bin_dir: Path) -> Path:
    """Shell wrapper so Chrome runs the host with this exact Python environment."""
    bin_dir.mkdir(parents=True, exist_ok=True)
    launcher = bin_dir / "ytclip-native-host"
    lines = ["#!/bin/sh", "# Generated by `ytclip native install`."]
    if config := os.environ.get("YTCLIP_CONFIG"):
        lines.append(f"export YTCLIP_CONFIG={shlex.quote(config)}")
    lines.append(f'exec {shlex.quote(sys.executable)} -m ytclip.native.host "$@"')
    launcher.write_text("\n".join(lines) + "\n", encoding="utf-8")
    launcher.chmod(0o755)
    return launcher


def build_manifest(launcher: Path, extension_ids: list[str]) -> dict:
    return {
        "name": HOST_NAME,
        "description": "ytclip local clip queue",
        "path": str(launcher),
        "type": "stdio",
        "allowed_origins": [f"chrome-extension://{validate_extension_id(e)}/" for e in extension_ids],
    }


def install(bin_dir: Path, extension_ids: list[str] | None = None,
            home: Path | None = None) -> list[ManifestLocation]:
    ids = list(dict.fromkeys([DEFAULT_EXTENSION_ID, *(extension_ids or [])]))
    manifest = build_manifest(write_launcher(bin_dir), ids)
    locations = manifest_locations(home)
    for location in locations:
        location.path.parent.mkdir(parents=True, exist_ok=True)
        location.path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return locations


def uninstall(home: Path | None = None) -> list[Path]:
    removed = []
    for location in manifest_locations(home, include_missing=True):
        if location.path.exists():
            location.path.unlink()
            removed.append(location.path)
    return removed


def installed_manifest(home: Path | None = None) -> tuple[Path, dict] | None:
    for location in manifest_locations(home):
        if location.path.exists():
            try:
                return location.path, json.loads(location.path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                return location.path, {}
    return None
